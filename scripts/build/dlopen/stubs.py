"""Generate lazy dlopen stubs for the functions of shared libraries.

    stubs.py --arch x86_64|i386|aarch64 --prefix NAME --out DIR
             [--fail FUNCTION=VALUE]... [--mirror SONAME:DATA_FILE]... [--whole]
             SONAME:FUNCTIONS_FILE...

For each library, FUNCTIONS_FILE lists the function names to stub, one per
line. The output is DIR/NAME-stubs.S and DIR/NAME-resolve.c, to be compiled
into one static library that stands in for the shared ones at link time.

Every stub is a jump through a table entry. The entry first points at a lazy
thunk that saves the argument registers, resolves the whole table of that
library with dlopen and dlsym, restores the registers and jumps again; the
arguments are never touched, so variadic functions work like any other. A
library or symbol that is missing resolves to a function returning 0, which
is how most APIs report failure (a NULL display, a NULL main loop). Where 0
means success, --fail says what the function returns instead: an integer
(ALSA's snd_pcm_open: -ENOENT) or the name of a C function, compiled with
the stubs, that takes the missing function's place.

A stub cannot stand in for exported data. --mirror defines the variables
DATA_FILE lists ("name size" per line) and copies the library's values into
them once it is loaded; PREFIX_mirror() copies them again, for data the
library sets later (GStreamer's types, set by gst_init).

With --whole, a library that lacks any of the stubbed functions (an older
version) counts as missing altogether, for callers that cannot cope with
some of its functions returning 0 (libwayland: Qt's Wayland client uses
what it was built against). PREFIX_available(LIB) says whether library LIB
is used.

Runs on Python 3.5 and later, the oldest being Ubuntu 16.04's.
"""
import argparse
import re
from pathlib import Path

HEADER = '/* Generated by scripts/build/dlopen/stubs.py; do not edit. */\n'


def stubs_x86_64(prefix, libs):
    out = [HEADER, '\t.text\n']
    for lib, (_, names) in enumerate(libs):
        table = '%s_table_%d' % (prefix, lib)
        for i, name in enumerate(names):
            lazy = '%s_lazy_%d_%d' % (prefix, lib, i)
            slot = '%s+%d(%%rip)' % (table, 8 * i)
            out.append('\t.globl %s\n\t.type %s,@function\n%s:\n\tjmp *%s\n\t.size %s,.-%s\n'
                       % (name, name, name, slot, name, name))
            # The entry rsp is 8 mod 16; seven pushes and 128 bytes keep the
            # call to the resolver 16-byte aligned.
            out.append('\t.globl %s\n\t.hidden %s\n%s:\n' % (lazy, lazy, lazy))
            out.append('\tpush %rdi\n\tpush %rsi\n\tpush %rdx\n\tpush %rcx\n\tpush %r8\n\tpush %r9\n\tpush %rax\n'
                       '\tsub $128, %rsp\n')
            out.append(''.join('\tmovdqu %%xmm%d, %d(%%rsp)\n' % (r, 16 * r) for r in range(8)))
            out.append('\tmov $%d, %%edi\n\tcall %s_resolve\n' % (lib, prefix))
            out.append(''.join('\tmovdqu %d(%%rsp), %%xmm%d\n' % (16 * r, r) for r in range(8)))
            out.append('\tadd $128, %rsp\n'
                       '\tpop %rax\n\tpop %r9\n\tpop %r8\n\tpop %rcx\n\tpop %rdx\n\tpop %rsi\n\tpop %rdi\n')
            out.append('\tjmp *%s\n' % slot)
    out.append('\t.section .note.GNU-stack,"",@progbits\n')
    return ''.join(out)


def stubs_i386(prefix, libs):
    # Position-independent: %eax, which cdecl passes nothing in, holds the
    # GOT address the table is reached from.
    pc = '%s_pc' % prefix
    out = [HEADER, '\t.text\n%s:\n\tmovl (%%esp), %%eax\n\tret\n' % pc]
    for lib, (_, names) in enumerate(libs):
        table = '%s_table_%d' % (prefix, lib)
        for i, name in enumerate(names):
            lazy = '%s_lazy_%d_%d' % (prefix, lib, i)
            jump = ('\tcall %s\n\taddl $_GLOBAL_OFFSET_TABLE_, %%eax\n\tjmp *%s@GOTOFF+%d(%%eax)\n'
                    % (pc, table, 4 * i))
            out.append('\t.globl %s\n\t.type %s,@function\n%s:\n%s\t.size %s,.-%s\n'
                       % (name, name, name, jump, name, name))
            # cdecl: the arguments stay on the stack, below the return address.
            out.append('\t.globl %s\n\t.hidden %s\n%s:\n\tpushl $%d\n\tcall %s_resolve\n\taddl $4, %%esp\n%s'
                       % (lazy, lazy, lazy, lib, prefix, jump))
    out.append('\t.section .note.GNU-stack,"",@progbits\n')
    return ''.join(out)


def stubs_aarch64(prefix, libs):
    out = [HEADER, '\t.text\n']
    for lib, (_, names) in enumerate(libs):
        table = '%s_table_%d' % (prefix, lib)
        for i, name in enumerate(names):
            lazy = '%s_lazy_%d_%d' % (prefix, lib, i)
            slot = '%s+%d' % (table, 8 * i)
            # x16 and x17 are the intra-procedure-call scratch registers.
            jump = '\tadrp x16, %s\n\tldr x17, [x16, #:lo12:%s]\n\tbr x17\n' % (slot, slot)
            out.append('\t.globl %s\n\t.type %s,%%function\n\t.p2align 2\n%s:\n%s\t.size %s,.-%s\n'
                       % (name, name, name, jump, name, name))
            # Frame record, x0-x7, x8 (the indirect result) and q0-q7: 224
            # bytes, keeping sp 16-byte aligned.
            out.append('\t.globl %s\n\t.hidden %s\n\t.p2align 2\n%s:\n' % (lazy, lazy, lazy))
            out.append('\tstp x29, x30, [sp, #-224]!\n\tmov x29, sp\n')
            out.append(''.join('\tstp x%d, x%d, [sp, #%d]\n' % (r, r + 1, 16 + 8 * r) for r in range(0, 8, 2)))
            out.append('\tstr x8, [sp, #80]\n')
            out.append(''.join('\tstp q%d, q%d, [sp, #%d]\n' % (r, r + 1, 96 + 16 * r) for r in range(0, 8, 2)))
            out.append('\tmov w0, #%d\n\tbl %s_resolve\n' % (lib, prefix))
            out.append(''.join('\tldp q%d, q%d, [sp, #%d]\n' % (r, r + 1, 96 + 16 * r) for r in range(0, 8, 2)))
            out.append('\tldr x8, [sp, #80]\n')
            out.append(''.join('\tldp x%d, x%d, [sp, #%d]\n' % (r, r + 1, 16 + 8 * r) for r in range(0, 8, 2)))
            out.append('\tldp x29, x30, [sp], #224\n')
            out.append(jump)
    out.append('\t.section .note.GNU-stack,"",@progbits\n')
    return ''.join(out)


STUBS = {'x86_64': stubs_x86_64, 'i386': stubs_i386, 'aarch64': stubs_aarch64}


def mirror(prefix, mirrors):
    """Definitions of the mirrored data and PREFIX_mirror(), which copies it."""
    out = [''.join('char %s[%d] __attribute__((aligned(16)));\n' % (name, size) for _, name, size in mirrors)]
    out.append('static const struct { const char *soname, *name; void *address; unsigned size; } %s_mirrors[] = {\n%s};\n\n'
               % (prefix, ''.join('    { "%s", "%s", %s, %d },\n' % (soname, name, name, size)
                                  for soname, name, size in mirrors) or '    { NULL, NULL, NULL, 0 },\n'))
    out.append('''/* Copies the data of the libraries already loaded. Where the library binds
   to the definition here (an executable that exports it), there is nothing
   to copy. */
HIDDEN void PREFIX_mirror(void)
{
    unsigned i;
    for (i = 0; i < COUNT; ++i) {
        void *handle = dlopen(PREFIX_mirrors[i].soname, RTLD_NOW | RTLD_NOLOAD);
        void *source = handle ? dlsym(handle, PREFIX_mirrors[i].name) : NULL;
        if (source && source != PREFIX_mirrors[i].address)
            memcpy(PREFIX_mirrors[i].address, source, PREFIX_mirrors[i].size);
        if (handle)
            dlclose(handle);
    }
}

'''.replace('PREFIX', prefix).replace('COUNT', str(len(mirrors))))
    return ''.join(out)


def resolver(prefix, libs, fails, mirrors, whole):
    # The tables, thunks and resolver are hidden: the stubs reach them
    # without the GOT or PLT, also when linked into a shared object.
    out = [HEADER, '#include <dlfcn.h>\n#include <stddef.h>\n#include <string.h>\n\n'
                   '#define HIDDEN __attribute__((visibility("hidden")))\n\n',
           mirror(prefix, mirrors),
           'static long %s_zero(void) { return 0; }\n' % prefix]
    missing = {}
    for name, value in sorted(fails.items()):
        if re.match(r'^-?\d+$', value):
            missing[name] = '%s_fail_%s' % (prefix, name)
            out.append('static long %s(void) { return %s; }\n' % (missing[name], value))
        else:
            missing[name] = value
            out.append('extern char %s[];\n' % value)
    out.append('\n')
    for lib, (soname, names) in enumerate(libs):
        lazies = ['%s_lazy_%d_%d' % (prefix, lib, i) for i in range(len(names))]
        out.append(''.join('extern HIDDEN char %s[];\n' % lazy for lazy in lazies))
        out.append('HIDDEN void *%s_table_%d[] = {\n%s};\n' % (prefix, lib, ''.join('    %s,\n' % lazy for lazy in lazies)))
        out.append('static const char *const %s_names_%d[] = {\n%s};\n'
                   % (prefix, lib, ''.join('    "%s",\n' % name for name in names)))
        out.append('static void *const %s_missing_%d[] = {\n%s};\n\n'
                   % (prefix, lib, ''.join('    (void *)%s,\n' % missing.get(name, prefix + '_zero') for name in names)))
    count = len(libs)
    out.append('static void *const *const %s_all_missing[] = { %s };\n'
               % (prefix, ', '.join('%s_missing_%d' % (prefix, lib) for lib in range(count))))
    out.append('static const char *const %s_sonames[] = { %s };\n'
               % (prefix, ', '.join('"%s"' % soname for soname, _ in libs)))
    out.append('static void **const %s_tables[] = { %s };\n'
               % (prefix, ', '.join('%s_table_%d' % (prefix, lib) for lib in range(count))))
    out.append('static const char *const *const %s_all_names[] = { %s };\n'
               % (prefix, ', '.join('%s_names_%d' % (prefix, lib) for lib in range(count))))
    out.append('static const unsigned %s_counts[] = { %s };\n'
               % (prefix, ', '.join(str(len(names)) for _, names in libs)))
    out.append('static const int %s_whole = %d;\n\n' % (prefix, 1 if whole else 0))
    out.append('''/* The library LIB, or NULL where it is missing; with --whole also where any
   stubbed function is missing from it, an older version. */
static void *PREFIX_open(int lib)
{
    void *handle = dlopen(PREFIX_sonames[lib], RTLD_NOW | RTLD_GLOBAL);
    unsigned i;
    for (i = 0; handle && PREFIX_whole && i < PREFIX_counts[lib]; ++i) {
        if (!dlsym(handle, PREFIX_all_names[lib][i])) {
            dlclose(handle);
            handle = NULL;
        }
    }
    return handle;
}

/* Called by a lazy thunk: fills the table of library LIB. Concurrent first
   calls may both resolve; they write the same values. */
#if defined(__i386__) || defined(__x86_64__)
__attribute__((force_align_arg_pointer))
#endif
__attribute__((used)) HIDDEN
void PREFIX_resolve(int lib)
{
    void *handle = PREFIX_open(lib);
    unsigned i;
    for (i = 0; i < PREFIX_counts[lib]; ++i) {
        void *address = handle ? dlsym(handle, PREFIX_all_names[lib][i]) : NULL;
        PREFIX_tables[lib][i] = address ? address : PREFIX_all_missing[lib][i];
    }
    PREFIX_mirror();
}

/* Whether library LIB is used, for callers that want to ask first. */
int PREFIX_available(int lib)
{
    return PREFIX_open(lib) != NULL;
}
'''.replace('PREFIX', prefix))
    return ''.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--arch', required=True, choices=sorted(STUBS))
    parser.add_argument('--prefix', required=True)
    parser.add_argument('--out', required=True)
    parser.add_argument('--fail', action='append', default=[], metavar='FUNCTION=VALUE')
    parser.add_argument('--mirror', action='append', default=[], metavar='SONAME:DATA_FILE')
    parser.add_argument('--whole', action='store_true')
    parser.add_argument('libs', nargs='+', metavar='SONAME:FUNCTIONS_FILE')
    args = parser.parse_args()
    libs = []
    seen = set()
    for spec in args.libs:
        soname, path = spec.split(':', 1)
        names = []
        for word in Path(path).read_text().split():
            if not re.match(r'^[A-Za-z_]\w*$', word):
                raise SystemExit('%s: not a function name: %r' % (path, word))
            # A function two libraries export is stubbed once, from the first.
            if word not in seen:
                seen.add(word)
                names.append(word)
        libs.append((soname, names))
    fails = dict(spec.split('=', 1) for spec in args.fail)
    unknown = sorted(set(fails) - seen)
    if unknown:
        raise SystemExit('--fail for functions that are not stubbed: %s' % ', '.join(unknown))
    mirrors = []
    for spec in args.mirror:
        soname, path = spec.split(':', 1)
        for line in Path(path).read_text().splitlines():
            name, size = line.split()
            # Data two libraries export is mirrored once, from the first.
            if name not in seen and int(size, 0) > 0:
                seen.add(name)
                mirrors.append((soname, name, int(size, 0)))
    out = Path(args.out)
    if not out.is_dir():
        out.mkdir(parents=True)
    (out / ('%s-stubs.S' % args.prefix)).write_text(STUBS[args.arch](args.prefix, libs))
    (out / ('%s-resolve.c' % args.prefix)).write_text(resolver(args.prefix, libs, fails, mirrors, args.whole))
    print(', '.join('%s: %d' % (soname, len(names)) for soname, names in libs))


if __name__ == '__main__':
    main()
