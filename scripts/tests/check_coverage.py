# --- gap files (grouped by module), restricted to selected modules ---
#
# One per version, suffixed like the databases.
def write_gap(major, d):
    s = only if only else {m for m in d.values()}
    # Against the sources that build against this version.
    seen = used_for(major)
    g = sorted((c for c, m in d.items() if c not in seen and m in s),
               key=lambda c: (d[c], c))
    name = "coverage-gap.txt" if major == 5 else "coverage-gap-qt%d.txt" % major
    with io.open(os.path.join(SCRIPTS, name), "w", encoding="utf-8", newline="\n") as f:
        f.write("# %d Qt %d classes not yet referenced by %s/\n"
                % (len(g), major,
                   os.path.relpath(SOURCE_DIRS.get(major, TESTS), ROOT).replace("\\", "/")))
        f.write("# (regenerate with: make check-coverage%s)\n" %
                (" MODULES=" + ",".join(sorted(only)) if only else ""))
        cur = None
        for c in g:
            if d[c] != cur:
                cur = d[c]
                f.write("\n## %s\n" % cur)
            f.write("%s\n" % c)
    return name, len(g)

