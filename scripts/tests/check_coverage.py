# Filled by prune_unreachable() so the report names what it removed.
removed_by_reason = defaultdict(dict)


def print_unreachable_summary(majors):
    """Say what left the denominator, per version and per reason.

    Printed every run rather than behind a flag. A metric that quietly shrinks
    its own denominator is the same failure as one that quietly inflates its
    numerator, and this file has already been on the wrong side of that once.
    """
    shown = [m for m in majors if removed_by_reason.get(m)]
    if not shown:
        return
    print()
    print("outside the denominator, as unreachable on anything this kit builds:")
    for major in shown:
        reasons = removed_by_reason[major]
        print("  Qt %d  %d classes" % (major, sum(reasons.values())))
        for reason, n in sorted(reasons.items(), key=lambda kv: -kv[1]):
            print("        %4d  %s" % (n, reason))


def unreachable_for(major):
    out = set()
    for classes in UNREACHABLE.get(major, {}).values():
        out |= set(classes)
    return out


def prune_unreachable(d, major):
    """Drop the classes above from a class->module database.

    Every name is checked against the database on the way through. A class that
    is not there means the list has drifted from the Qt it describes - a typo,
    or a database regenerated from a different release - and that is worth
    stopping for, because the alternative is a denominator quietly one class
    larger than intended.
    """
    if major not in removed_by_reason:
        for reason, classes in UNREACHABLE.get(major, {}).items():
            unknown = [c for c in classes if c not in d]
            if unknown:
                sys.exit("check_coverage: UNREACHABLE[%d] names %d class(es) "
                         "absent from the Qt %d database:\n  %s\nEither the "
                         "database was regenerated from a different Qt or the "
                         "name is a typo."
                         % (major, len(unknown), major, "\n  ".join(sorted(unknown))))
            removed_by_reason[major][reason] = len(classes)
    return {c: m for c, m in d.items() if c not in unreachable_for(major)}


