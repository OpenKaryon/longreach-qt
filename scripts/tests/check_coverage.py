EXCLUDED_PATHS = {4: NON_QT4, 5: QT4_ONLY, 6: QT4_ONLY}


def require_paths():
    """Fail loudly if an excluded path no longer exists.

    A stale exclusion does not announce itself - it silently credits a version
    with sources it never builds, which is the exact way this list rotted the
    last time. Renaming or moving one of these files is meant to break the
    coverage run rather than to move the number.
    """
    missing = []
    for paths in (QT4_ONLY, NON_QT4):
        for rel in paths:
            full = os.path.join(TESTS, rel.rstrip("/"))
            ok = os.path.isdir(full) if rel.endswith("/") else os.path.isfile(full)
            if not ok:
                missing.append(rel)
    if missing:
        sys.exit("check_coverage: EXCLUDED_PATHS names %d path(s) that no longer "
                 "exist under tests/:\n  %s\nUpdate the list to match the "
                 "per-version SOURCES in the app CMakeLists.txt files."
                 % (len(missing), "\n  ".join(sorted(set(missing)))))


def require_qt4_naming():
    """The other direction: a *new* Qt 4-only file that nobody excluded.

    require_paths() catches a listed file that moved; it cannot catch a file
    that was added and never listed, which is the same silent inflation from the
    other end - and it happened immediately, the first time this suite gained a
    Qt 4-only check file after the list was written.

    The suite names those files by convention (checks_*_qt4.cpp, qt4_*.cpp,
    qml_qt4/), so the convention is what gets enforced: nothing with qt4 in its
    path may be scanned for Qt 5 or Qt 6. Deliberately one-directional - the
    qt6_*.cpp files are compiled on Qt 5 as well, guarded internally, so there is
    no matching rule to write for them.
    """
    stray = sorted(os.path.relpath(p, TESTS).replace("\\", "/")
                   for p in source_files(5)
                   if "qt4" in os.path.relpath(p, TESTS).replace("\\", "/").lower())
    if stray:
        sys.exit("check_coverage: %d Qt 4-only source(s) are still counted "
                 "towards Qt 5 and Qt 6:\n  %s\nAdd them to QT4_ONLY."
                 % (len(stray), "\n  ".join(stray)))


require_paths()


def source_files(major):
    out = []
    for ext in ("*.cpp", "*.h", "*.qml"):
        out += glob.glob(os.path.join(SOURCE_DIRS[major], "**", ext), recursive=True)
    excluded = EXCLUDED_PATHS.get(major, ())
    def wanted(p):
        rel = os.path.relpath(p, SOURCE_DIRS[major]).replace("\\", "/")
        if not keep(p):
            return False
        for e in excluded:
            if rel == e or (e.endswith("/") and rel.startswith(e)):
                return False
        return True
    return [f for f in out if wanted(f)]


