# --- per-platform mode ----------------------------------------------------
def platform_tally(name):
    """-> (applicable classes, covered there, list of classes lost to guards)"""
    prof = PLATFORMS[name]
    applicable = [c for c, m in db.items() if m not in prof["absent_modules"]]
    hit, guarded_out = 0, []
    for c in applicable:
        if c not in covered:
            continue
        if covered_on(c, prof):
            hit += 1
        else:
            guarded_out.append(c)
    return len(applicable), hit, sorted(guarded_out)

