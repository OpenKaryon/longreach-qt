# --- guard evaluation -----------------------------------------------------
#
# Each reference keeps the preprocessor conditions around it, so a class used
# only under #ifdef Q_OS_WIN is uncovered on Linux; one reachable occurrence is
# enough. The evaluator handles defined(X), X, QT_CONFIG(f), !, &&, || and
# parentheses; anything else counts as true rather than deleting coverage.
IFDEF = re.compile(r"^\s*#\s*(ifdef|ifndef|elif|else|endif|if)\b\s*(.*)$")

# Condition tokens, longest first; unknown ones mean reachable (eval_guard).
_TOKEN = re.compile(r"&&|\|\||[()!]|[A-Za-z_][A-Za-z0-9_]*|[0-9]+|\s+")


def eval_guard(expr, defines, features):
    """Evaluate an #if condition against a platform profile.

    Handles what tests/ actually uses: defined(X), defined X, a bare X,
    QT_CONFIG(f), !, &&, ||, parentheses and integer literals. Anything else
    yields True.

    Erring towards "reachable" is deliberate. Treating an unmodelled guard as
    false would quietly remove classes from the count with nothing to show for
    it, whereas over-counting is self-correcting: a class wrongly reported as
    covered on a target turns into a compile failure the first time anyone
    builds that target.
    """
    toks = []
    pos = 0
    while pos < len(expr):
        m = _TOKEN.match(expr, pos)
        if not m:
            return True                       # character we do not model
        pos = m.end()
        tok = m.group(0)
        if tok.strip():
            toks.append(tok)

    out = []
    i = 0
    while i < len(toks):
        t = toks[i]
        if t == "defined":
            j = i + 1
            if j < len(toks) and toks[j] == "(":
                if j + 2 >= len(toks) or toks[j + 2] != ")":
                    return True
                name, i = toks[j + 1], j + 3
            else:
                if j >= len(toks):
                    return True
                name, i = toks[j], j + 1
            out.append("True" if name in defines else "False")
        elif t == "QT_CONFIG":
            if i + 3 >= len(toks) or toks[i + 1] != "(" or toks[i + 3] != ")":
                return True
            out.append("True" if features.get(toks[i + 2], False) else "False")
            i += 4
        elif t == "&&":
            out.append("and")
            i += 1
        elif t == "||":
            out.append("or")
            i += 1
        elif t == "!":
            out.append("not")
            i += 1
        elif t in ("(", ")"):
            out.append(t)
            i += 1
        elif t.isdigit():
            out.append("True" if int(t) else "False")
            i += 1
        else:
            out.append("True" if t in defines else "False")
            i += 1
    try:
        return bool(eval(" ".join(out), {"__builtins__": {}}, {}))
    except Exception:
        return True

def scan_with_guards(text):
    """-> {class name: [guard-stack, ...]}, one stack per occurrence."""
    out = defaultdict(list)
    stack = []               # list of (condition, negate_previous_branches)
    for line in text.splitlines():
        m = IFDEF.match(line)
        if m:
            kw, rest = m.group(1), m.group(2)
            rest = rest.split("//")[0].split("/*")[0].strip()
            if kw == "ifdef":
                stack.append([("defined(%s)" % rest, [])])
            elif kw == "ifndef":
                stack.append([("!defined(%s)" % rest, [])])
            elif kw == "if":
                stack.append([(rest, [])])
            elif kw == "elif" and stack:
                prior = [c for c, _ in stack[-1]]
                stack[-1].append((rest, prior))
            elif kw == "else" and stack:
                prior = [c for c, _ in stack[-1]]
                stack[-1].append(("1", prior))
            elif kw == "endif" and stack:
                stack.pop()
            continue
        found = QCLASS.findall(line)
        if not found:
            continue
        guards = [lvl[-1] for lvl in stack]   # innermost branch of each level
        for cls in found:
            out[cls].append(guards)
    return out

def scan_sources(paths):
    seen, occ = set(), defaultdict(list)
    for f in paths:
        text = strip_comments(io.open(f, encoding="utf-8", errors="ignore").read())
        for cls, stacks in scan_with_guards(text).items():
            seen.add(cls)
            occ[cls].extend(stacks)
    return seen, occ


