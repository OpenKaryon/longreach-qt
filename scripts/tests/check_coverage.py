def covered_on(cls, prof):
    """Is any occurrence of cls reachable under this platform profile?"""
    for guards in occurrences.get(cls, []):
        ok = True
        for cond, negated in guards:
            if not eval_guard(cond, prof["defines"], prof["features"]):
                ok = False
                break
            if any(eval_guard(p, prof["defines"], prof["features"]) for p in negated):
                ok = False   # an earlier branch of the same #if won
                break
        if ok:
            return True
    return False

