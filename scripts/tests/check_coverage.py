#   --only=mod1,mod2   the headline % over these modules
#   --threshold=NN     exit 1 below NN% (the lowest version counts)
#   --gate             --threshold with RELEASE_THRESHOLD, as CI uses
#   --platform=NAME    what is covered on that target, where modules and
#                      platform guards differ; list or all
#   --qt=N             one version (4, 5 or 6) instead of all
#   --compare          what changed between the versions
#
