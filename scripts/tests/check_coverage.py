# --- scan the test sources for Qt class references ---
#
# Names only in comments do not count; strip_comments() knows string literals,
# so "file:///x" is not taken for a comment.
def strip_comments(text):
    out = []
    i, n = 0, len(text)
    in_string = None  # None, or the quote character we're inside
    while i < n:
        c = text[i]
        if in_string:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == in_string:
                in_string = None
            i += 1
            continue
        if c == '"' or c == "'":
            in_string = c
            out.append(c)
            i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            j = text.find("\n", i)
            i = n if j == -1 else j  # keep the newline itself for line counting
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            j = text.find("*/", i + 2)
            i = n if j == -1 else j + 2
            continue
        out.append(c)
        i += 1
    return "".join(out)

