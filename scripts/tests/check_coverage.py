# Platform profiles, measured from the built images: modules from the
# libQt5<Module>.a files in each SDK, features from the installed QT_FEATURE_*.
# OpenGL and SSL are on everywhere; DTLS only with OpenSSL (Schannel and
# SecureTransport have no DTLS backend); Quick3D everywhere. Re-measure after
# changing a configure line.
COMMON_FEATURES = {"opengl": True, "ssl": True, "dtls": False, "sctp": False}

# Modules only some targets have; the rest exist everywhere.
PLATFORM_MODULES = {
    "windows": {"qtwinextras"},
    "linux":   {"qtx11extras", "qtwayland"},
    "macos":   {"qtmacextras"},
}
NEVER_BUILT = set()

def _profile(os_name, defines, features=None):
    modules = set().union(*PLATFORM_MODULES.values()) - PLATFORM_MODULES[os_name]
    merged_features = dict(COMMON_FEATURES)
    if features:
        merged_features.update(features)
    return {"os": os_name, "defines": defines, "absent_modules": modules | NEVER_BUILT,
            "features": merged_features}

