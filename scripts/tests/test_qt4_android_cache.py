ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("qt4_cache", ROOT / "scripts/build/qt4-android/cache-inputs.py")
cache = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cache)
source_spec = importlib.util.spec_from_file_location("qt4_source", ROOT / "scripts/build/qt4-android/prepare-source.py")
source = importlib.util.module_from_spec(source_spec)
source_spec.loader.exec_module(source)

MAKEFILE = """# Generated by qmake, date: today
CC = clang
CXX = clang++
DEFINES = -DQT_VERSION_MAJOR=4
CFLAGS = -O2
CXXFLAGS = -O2 -std=gnu++23
INCPATH = -I/sdk/include
LINK = cxx
LFLAGS = -shared
LIBS = /sdk/libQtCore.a
"""


class CacheInputs(unittest.TestCase):
    def test_compiler_flags_mkspec_and_headers_invalidate_objects(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            runtime, sdk = root / "runtime", root / "sdk"
            files = [root / "compiler", runtime / "target.sh", runtime / "bin/cxx", runtime / "bin/cc",
                     runtime / "include/c++/v1/vector", runtime / "sysroot/usr/include/stdio.h",
                     sdk / "mkspecs/android-longreach-clang/qmake.conf",
                     sdk / "mkspecs/android-longreach-clang/qplatformdefs.h", sdk / "include/QtCore/qconfig.h"]
            for file in files:
                file.parent.mkdir(parents=True, exist_ok=True)
                file.write_text("old")
            with patch.object(cache.shutil, "which", return_value=str(root / "compiler")), patch.object(cache.subprocess, "check_output", return_value="clang 21.1.8"):
                def key():
                    return cache.fingerprint(cache.client_compile_inputs(sdk, runtime))
                initial = key()
                self.assertEqual(initial, key())
                for file in files:
                    file.write_text("changed")
                    self.assertNotEqual(initial, key(), str(file))
                    file.write_text("old")
                (sdk / "lib").mkdir()
                (sdk / "lib/QtCore.a").write_text("new link input")
                self.assertEqual(initial, key(), "Archive-only changes must retain compilation objects")
                saved = root / "saved"
                self.assertTrue(cache.needs_clean(saved, initial))
                saved.write_text(initial)
                self.assertFalse(cache.needs_clean(saved, initial))
                self.assertTrue(cache.needs_clean(saved, cache.fingerprint([initial, "new flags"])))

    def test_missing_or_empty_input_directories_are_not_empty_fingerprints(self):
        with tempfile.TemporaryDirectory() as temporary:
            base = Path(temporary) / 'missing'
            with self.assertRaisesRegex(ValueError, 'Missing cache input directory'):
                cache.tree_inputs(base)
            base.mkdir()
            with self.assertRaisesRegex(ValueError, 'Empty cache input directory'):
                cache.tree_inputs(base)

    def test_runtime_crt_builtins_platform_and_linker_are_link_inputs(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            runtime, prefix = root / 'runtime', root / 'sdk'
            paths = [runtime / name for name in ('target.sh', 'bin/cxx', 'bin/cc',
                     'lib/crt-android.o', 'lib/tmpfile-android.o', 'lib/libc++_shared.so',
                     'lib/libclang_rt.builtins.a', 'sysroot/usr/lib/x86_64-linux-android/21/crtbegin_so.o',
                     'sysroot/usr/lib/x86_64-linux-android/21/crtend_so.o', 'sysroot/usr/lib/x86_64-linux-android/21/libc.so')]
            compiler, linker = root / 'tools/clang', root / 'tools/ld.lld'
            archive = prefix / 'lib/libQtCore.a'
            for path in paths + [compiler, linker, archive]:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text('old')
            with patch.object(cache.shutil, 'which', return_value=str(compiler)):
                def key():
                    return cache.fingerprint(cache.client_link_inputs(runtime, [archive], 'x86_64'))
                original = key()
                for path in paths + [linker, archive]:
                    path.write_text('changed')
                    self.assertNotEqual(original, key(), str(path))
                    path.write_text('old')
                linker.unlink()
                with self.assertRaisesRegex(ValueError, 'Missing compiler-adjacent linker'):
                    key()

    def test_effective_makefile_compile_inputs_ignore_date_and_link_options(self):
        key = cache.fingerprint(cache.makefile_compile_inputs(MAKEFILE))
        for old, new in (('today', 'tomorrow'), ('-shared', '-shared -s'),
                         ('/sdk/libQtCore.a', '/sdk/new-libQtCore.a')):
            self.assertEqual(key, cache.fingerprint(cache.makefile_compile_inputs(MAKEFILE.replace(old, new))))
        for old, new in (('-DQT_VERSION_MAJOR=4', '-DQT_VERSION_MAJOR=4 -DSMOKE_HAVE_X'),
                         ('-O2 -std=gnu++23', '-O3 -std=gnu++23'),
                         ('-I/sdk/include', '-I/new-sdk/include')):
            self.assertNotEqual(key, cache.fingerprint(cache.makefile_compile_inputs(MAKEFILE.replace(old, new))))
        self.assertEqual(cache.makefile_compile_inputs(MAKEFILE)['CXXFLAGS'],
                         cache.makefile_compile_inputs(MAKEFILE.replace('-O2 -std=gnu++23', '-O2 \\\n-std=gnu++23'))['CXXFLAGS'])
        with self.assertRaisesRegex(ValueError, 'Missing qmake compile assignments'):
            cache.makefile_compile_inputs('LIBS = libQtCore.a\n')

    def test_actual_client_order_retains_objects_for_link_only_changes(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            output, obj = root / 'libfixture.so', root / 'fixture.o'
            calls = []
            makefile = MAKEFILE
            fail_make = False
            def run(arguments, directory):
                nonlocal fail_make
                calls.append(tuple(arguments))
                self.assertEqual(directory, root)
                if arguments[0] == 'qmake':
                    (root / 'Makefile').write_text(makefile)
                elif arguments == ['make', 'clean']:
                    obj.unlink(missing_ok=True)
                    output.unlink(missing_ok=True)
                else:
                    if fail_make:
                        raise RuntimeError('fixture make failure')
                    if obj.exists():
                        self.assertFalse(output.exists(), 'Changed link inputs did not force relink')
                    if not obj.exists():
                        obj.write_text('compiled')
                    output.write_text('linked')
            def build(link='link-v1'):
                cache.build_client(root, 'fixture', ['qmake', 'fixture.pro'], 'compiler-v1', link, 2, run)
            build()
            self.assertEqual(calls, [('qmake', 'fixture.pro'), ('make', 'clean'), ('make', '-j2')])
            calls.clear()
            # The recorder models an up-to-date make separately from a relink.
            def warm_run(arguments, directory):
                if arguments == ['make', '-j2']:
                    calls.append(tuple(arguments))
                    return
                run(arguments, directory)
            cache.build_client(root, 'fixture', ['qmake', 'fixture.pro'], 'compiler-v1', 'link-v1', 2, warm_run)
            self.assertEqual(calls, [('qmake', 'fixture.pro'), ('make', '-j2')])
            calls.clear()
            timestamp = obj.stat().st_mtime_ns
            build('link-v2')
            self.assertEqual(calls, [('qmake', 'fixture.pro'), ('make', '-j2')])
            self.assertEqual(obj.stat().st_mtime_ns, timestamp)
            calls.clear()
            makefile = MAKEFILE.replace('-shared', '-shared -s')
            build('link-v2')
            self.assertEqual(calls, [('qmake', 'fixture.pro'), ('make', '-j2')])
            self.assertEqual(obj.stat().st_mtime_ns, timestamp)
            calls.clear()
            makefile = MAKEFILE.replace('-DQT_VERSION_MAJOR=4', '-DQT_VERSION_MAJOR=4 -DSMOKE_HAVE_X')
            saved = (root / '.longreach-sdk-compile-inputs').read_text()
            fail_make = True
            with self.assertRaisesRegex(RuntimeError, 'fixture make failure'):
                build('link-v2')
            self.assertEqual(calls, [('qmake', 'fixture.pro'), ('make', 'clean'), ('make', '-j2')])
            self.assertEqual((root / '.longreach-sdk-compile-inputs').read_text(), saved)
            calls.clear()
            fail_make = False
            build('link-v2')
            self.assertEqual(calls, [('qmake', 'fixture.pro'), ('make', 'clean'), ('make', '-j2')])


class SourceRefresh(unittest.TestCase):
    def setup_source(self, root):
        repo, tree, archive = root / 'repo', root / 'tree', root / 'qt.tar.gz'
        helper = repo / 'scripts/build/qt4-android'
        helper.mkdir(parents=True)
        shutil.copyfile(ROOT / 'scripts/build/qt4-android/prepare-source.py', helper / 'prepare-source.py')
        script = helper / 'patch-qtcore.py'
        self.archive(archive)
        script.write_text("from pathlib import Path\nPath('src/unit.cpp').write_text('patched-v1')\n")
        return repo, tree, archive, script

    def archive(self, archive, project='DEFINES += OLD'):
        with tarfile.open(archive, 'w:gz') as output:
            for name, text in {'configure': '#!/bin/sh\n', 'src/unit.cpp': 'pristine',
                               'src/unchanged.cpp': 'unchanged', 'src/project.pro': project,
                               'src/corelib/global/qconfig.h': 'pristine configuration'}.items():
                member = tarfile.TarInfo('qt-4.8.7/' + name)
                member.size = len(text.encode())
                member.mode = 0o755 if name == 'configure' else 0o644
                output.addfile(member, io.BytesIO(text.encode()))

    def test_patch_revision_removal_and_added_file_cleanup_retain_objects(self):
        with tempfile.TemporaryDirectory() as temporary:
            repo, tree, archive, script = self.setup_source(Path(temporary))
            self.assertTrue(source.prepare(repo, archive, tree, 'core', 21))
            obj = tree / 'src/unit.o'
            obj.write_text('retained object')
            (tree / 'Makefile').write_text('generated Makefile')
            config = tree / 'src/corelib/global/qconfig.h'
            config.write_text('generated configuration')
            (tree / '.donut-configured').touch()
            untouched = (tree / 'src/unchanged.cpp').stat().st_mtime_ns
            script.write_text("from pathlib import Path\nPath('src/unit.cpp').write_text('patched-v2')\nPath('src/added.cpp').write_text('added')\n")
            self.assertTrue(source.prepare(repo, archive, tree, 'core', 21))
            self.assertEqual((tree / 'src/unit.cpp').read_text(), 'patched-v2')
            self.assertEqual(config.read_text(), 'generated configuration')
            self.assertTrue((tree / '.donut-configured').exists(), 'Source-only revision needlessly invalidated configuration')
            self.assertEqual((tree / 'src/unchanged.cpp').stat().st_mtime_ns, untouched)
            script.write_text('# removed all edits\n')
            source.prepare(repo, archive, tree, 'core', 21)
            self.assertEqual((tree / 'src/unit.cpp').read_text(), 'pristine')
            self.assertFalse((tree / 'src/added.cpp').exists())
            self.assertEqual(obj.read_text(), 'retained object')
            self.assertEqual((tree / 'Makefile').read_text(), 'generated Makefile')
            with patch.object(source, 'apply_recipe', side_effect=AssertionError('unchanged recipe re-applied')):
                self.assertFalse(source.prepare(repo, archive, tree, 'core', 21))

    def test_changed_archive_project_forces_reconfigure(self):
        with tempfile.TemporaryDirectory() as temporary:
            repo, tree, archive, script = self.setup_source(Path(temporary))
            source.prepare(repo, archive, tree, 'core', 21)
            (tree / '.donut-configured').touch()
            (tree / '.longreach-configuration').write_text('old')
            before = (tree / '.longreach-source-configuration').read_text()
            self.archive(archive, project='DEFINES += NEW')
            source.prepare(repo, archive, tree, 'core', 21)
            self.assertFalse((tree / '.donut-configured').exists())
            self.assertFalse((tree / '.longreach-configuration').exists())
            self.assertNotEqual(before, (tree / '.longreach-source-configuration').read_text())

    def test_failed_recipe_leaves_live_tree_and_receipt_unchanged(self):
        with tempfile.TemporaryDirectory() as temporary:
            repo, tree, archive, script = self.setup_source(Path(temporary))
            source.prepare(repo, archive, tree, 'core', 21)
            before = (tree / source.STATE).read_bytes()
            script.write_text("from pathlib import Path\nPath('src/unit.cpp').write_text('partial patch')\nraise RuntimeError('fixture patch failure')\n")
            with self.assertRaises(source.subprocess.CalledProcessError):
                source.prepare(repo, archive, tree, 'core', 21)
            self.assertEqual((tree / source.STATE).read_bytes(), before)
            self.assertEqual((tree / 'src/unit.cpp').read_text(), 'patched-v1')

    def test_interrupted_sync_retries_before_accepting_recipe(self):
        with tempfile.TemporaryDirectory() as temporary:
            repo, tree, archive, script = self.setup_source(Path(temporary))
            source.prepare(repo, archive, tree, 'core', 21)
            before = (tree / source.STATE).read_bytes()
            script.write_text("from pathlib import Path\nPath('src/unit.cpp').write_text('patched-v2')\n")
            with patch.object(source.shutil, 'copyfile', side_effect=OSError('fixture sync interruption')):
                with self.assertRaisesRegex(OSError, 'fixture sync interruption'):
                    source.prepare(repo, archive, tree, 'core', 21)
            self.assertEqual((tree / source.STATE).read_bytes(), before)
            source.prepare(repo, archive, tree, 'core', 21)
            self.assertEqual((tree / 'src/unit.cpp').read_text(), 'patched-v2')

    def test_provenance_rejects_changed_recipe_and_changed_patched_source(self):
        with tempfile.TemporaryDirectory() as temporary:
            repo, tree, archive, script = self.setup_source(Path(temporary))
            source.prepare(repo, archive, tree, 'core', 21)
            prepared = source.verify_prepared(repo, archive, tree, 'core', 21)
            self.assertEqual(prepared['modified_source'], {'src/unit.cpp': source.digest(tree / 'src/unit.cpp')})
            (tree / 'src/unit.cpp').write_text('stale source')
            with self.assertRaisesRegex(RuntimeError, 'differ from their prepared generation'):
                source.verify_prepared(repo, archive, tree, 'core', 21)
            script.write_text('# new source recipe\n')
            with self.assertRaisesRegex(RuntimeError, 'another source recipe'):
                source.verify_prepared(repo, archive, tree, 'core', 21)

    @unittest.skipUnless(shutil.which('patch'), 'GNU patch needed for source refresh fixture')
    def test_real_patch_revision_and_removal_ignore_old_markers(self):
        with tempfile.TemporaryDirectory() as temporary:
            repo, tree, archive, script = self.setup_source(Path(temporary))
            script.write_text('# no Python edits\n')
            patches = repo / 'patches/qt4'
            for directory in ('all', 'android', 'linux-sarge-llvm'):
                (patches / directory).mkdir(parents=True)
            def patch_file(path, name, old, new):
                path.write_text(f'--- a/{name}\n+++ b/{name}\n@@ -1 +1 @@\n-{old}\n+{new}\n')
            # Patch input lines require a final newline like upstream sources.
            with tarfile.open(archive, 'w:gz') as output:
                for name, text in {'configure': '#!/bin/sh\n', 'src/unit.cpp': 'pristine\n',
                                   'src/unchanged.cpp': 'unchanged\n', 'src/color.cpp': 'color\n'}.items():
                    member = tarfile.TarInfo('qt/' + name)
                    member.size = len(text)
                    output.addfile(member, io.BytesIO(text.encode()))
            first = patches / 'all/03-static-gui-animation-registration.patch'
            patch_file(first, 'src/unit.cpp', 'pristine', 'first')
            patch_file(patches / 'all/04-script-tagged-frame-pointers.patch', 'src/unchanged.cpp', 'unchanged', 'frames')
            android = patches / 'android/01-example.patch'
            patch_file(android, 'src/unit.cpp', 'first', 'android')
            patch_file(patches / 'linux-sarge-llvm/01-xmlpatterns-color-mask.patch', 'src/color.cpp', 'color', 'masked')
            source.prepare(repo, archive, tree, 'quick', 21)
            self.assertEqual((tree / 'src/unit.cpp').read_text(), 'android\n')
            (tree / '.donut-static-gui-animation').touch()
            (tree / '.donut-script-frames').touch()
            obj = tree / 'src/unit.o'
            obj.write_text('retained object')
            android.unlink()
            source.prepare(repo, archive, tree, 'quick', 21)
            self.assertEqual((tree / 'src/unit.cpp').read_text(), 'first\n')
            patch_file(first, 'src/unit.cpp', 'pristine', 'revised')
            source.prepare(repo, archive, tree, 'quick', 21)
            self.assertEqual((tree / 'src/unit.cpp').read_text(), 'revised\n')
            self.assertEqual(obj.read_text(), 'retained object')
            source.verify_prepared(repo, archive, tree, 'quick', 21)


